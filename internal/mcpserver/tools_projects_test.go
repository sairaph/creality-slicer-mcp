// projectBundle writes a small synthetic Creality profile bundle with what a
// project needs (a printer with a bed, a process, two filaments).
func projectBundle(t *testing.T) string {
	t.Helper()
	root := filepath.Join(t.TempDir(), "profiles")
	type entry struct{ name, sub string }
	lists := map[string][]entry{}
	add := func(kind, name, body string) {
		file := name + ".json"
		if err := os.MkdirAll(filepath.Join(root, "Creality", kind), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(root, "Creality", kind, file), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
		lists[kind] = append(lists[kind], entry{name, kind + "/" + file})
	}
	add("machine", tpPrinter, fmt.Sprintf(`{"type":"machine","name":%q,"from":"system","instantiation":"true","setting_id":"90.4",
"printer_model":"Creality K2","printer_variant":"0.4","nozzle_diameter":["0.4"],
"printable_area":"0x0,260x0,260x260,0x260","printable_height":"250","nozzle_volume":"183",
"default_print_profile":%q,"default_filament_profile":[%q],"thumbnails":"96x96/PNG, 300x300/PNG"}`, tpPrinter, tpProcess, tpPLA))
	add("process", tpProcess, fmt.Sprintf(`{"type":"process","name":%q,"from":"system","instantiation":"true","setting_id":"GP1",
"layer_height":"0.2","initial_layer_print_height":"0.2","wall_loops":"3","compatible_printers":[%q]}`, tpProcess, tpPrinter))
	fil := func(name, id, typ, colour string) string {
		return fmt.Sprintf(`{"type":"filament","name":%q,"from":"system","instantiation":"true","filament_id":%q,
"filament_type":[%q],"default_filament_colour":[%q],"nozzle_temperature":["215"],"compatible_printers":[%q]}`, name, id, typ, colour, tpPrinter)
	}
	add("filament", tpPLA, fil(tpPLA, "P001", "PLA", "#FFFFFF"))
	add("filament", tpPETG, fil(tpPETG, "P002", "PETG", "#000000"))
	add("filament", "Generic PLA @Creality K2 0.4 nozzle", fil("Generic PLA @Creality K2 0.4 nozzle", "GFL99", "PLA", "#FFFFFF"))
	var idx strings.Builder
	idx.WriteString(`{"name":"Creality","version":"9.0.0.1","description":"synthetic"`)
	for _, kind := range []string{"machine", "process", "filament"} {
		idx.WriteString(fmt.Sprintf(`,%q:[`, kind+"_list"))
		for i, e := range lists[kind] {
			if i > 0 {
				idx.WriteString(",")
			}
			idx.WriteString(fmt.Sprintf(`{"name":%q,"sub_path":%q}`, e.name, e.sub))
		}
		idx.WriteString("]")
	}
	idx.WriteString("}")
	if err := os.WriteFile(filepath.Join(root, "Creality.json"), []byte(idx.String()), 0o644); err != nil {
		t.Fatal(err)
	}
	return root
}

