// fakeSlicer stands in for the slicer process: it writes a G-code for the
// plate it is asked to slice. No real slicer runs in tests.
type fakeSlicer struct {
	mu      sync.Mutex
	calls   int
	block   chan struct{} // waited on before the run ends, when set
	killed  chan struct{} // closed when a blocked run is cancelled
	started chan struct{} // closed when the first run has begun
	once    sync.Once
	gcode   string // the G-code to write instead of sliceGCode, when set
}

func (f *fakeSlicer) Run(ctx context.Context, spec slicer.ExecSpec) (slicer.ExecResult, error) {
	f.mu.Lock()
	f.calls++
	f.mu.Unlock()
	if f.started != nil {
		f.once.Do(func() { close(f.started) })
	}
	if f.block != nil {
		select {
		case <-f.block:
		case <-ctx.Done():
			if f.killed != nil {
				close(f.killed)
			}
			return slicer.ExecResult{Killed: true}, nil
		}
	}
	plate, out := 1, ""
	for i, a := range spec.Args {
		switch a {
		case "--slice":
			if n, _ := strconv.Atoi(spec.Args[i+1]); n > 0 {
				plate = n
			}
		case "--outputdir":
			out = spec.Args[i+1]
		}
	}
	text := sliceGCode
	if f.gcode != "" {
		text = f.gcode
	}
	err := os.WriteFile(filepath.Join(out, fmt.Sprintf("plate_%d.gcode", plate)), []byte(text), 0o644)
	return slicer.ExecResult{}, err
}

// projFixture is a server over a real projects.Store in a temporary folder
// with a fake slicer process.
type projFixture struct {
	*fixture
	srv   *Server
	exec  *fakeSlicer
	stl   string
	store *projects.Store
	// builds counts the projects backends the server built.
	builds int
	// launcher stands in for the application launcher.
	launcher *fakeLauncher
	// wrap, set before the first call, wraps the store the server gets.
	wrap func(ProjectStore) ProjectStore
}

func newProjFixture(t *testing.T, opts ...func(*Config)) *projFixture {
	t.Helper()
	pf := &projFixture{exec: &fakeSlicer{}, launcher: &fakeLauncher{}}
	root := projectBundle(t)
	dir := t.TempDir()
	in := slicer.Install{
		Found: true, Supported: true, Version: "7.2.2", Build: "5483", Dialect: "v72",
		Dir: dir, Exe: filepath.Join(dir, "CrealityPrint.exe"), DataDir: filepath.Join(dir, "data"),
		ProfileVersion: "9.0.0.1", ProfileRoot: root,
	}
	fi := &fakeInstall{install: in}
	deps := Deps{
		Install:  fi,
		Launcher: pf.launcher,
		Texts:    func(string) (catalog.TextSource, error) { return fakeTexts{}, nil },
		NewProjects: func(in slicer.Install, ps ProfileStore, cat *catalog.Catalog) (ProjectBackend, error) {
			real, ok := ps.(*profiles.Store)
			if !ok {
				return ProjectBackend{}, fmt.Errorf("no preset store")
			}
			d, err := slicer.NewDialect("v72", cat.CLIFlag)
			if err != nil {
				return ProjectBackend{}, err
			}
			runner := &slicer.Runner{Exe: in.Exe, Dialect: d, Exec: pf.exec, TempDir: func() string { return t.TempDir() }}
			jobs := slicer.NewJobs(runner, filepath.Join(dir, "jobs"))
			st, err := projects.New(projects.Config{
				Root: filepath.Join(dir, "projects"), Install: in, Runner: runner, Jobs: jobs, Profiles: real, Catalog: cat,
			})
			if err != nil {
				return ProjectBackend{}, err
			}
			pf.store = st
			pf.builds++
			var store ProjectStore = st
			if pf.wrap != nil {
				store = pf.wrap(st)
			}
			return ProjectBackend{Store: store, Jobs: jobs}, nil
		},
	}
	pf.fixture = &fixture{install: fi, cfg: Config{Version: "1.2.3", Deps: deps}}
	for _, o := range opts {
		o(&pf.cfg)
	}
	pf.cs = sessionConfig(t, pf.cfg, func(s *Server) { pf.srv = s })
	t.Cleanup(func() { pf.srv.env.stopJobs() })
	pf.stl = filepath.Join(t.TempDir(), "cube.stl")
	if err := os.WriteFile(pf.stl, mesh.WriteBinarySTL(mesh.Box(20, 20, 20)), 0o644); err != nil {
		t.Fatal(err)
	}
	return pf
}

