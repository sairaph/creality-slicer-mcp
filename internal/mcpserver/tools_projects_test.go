// slice_project waits up to `wait` seconds in the foreground and hands over the
// job id when the slice takes longer.
func TestSliceProjectWaitsThenHandsOverTheJob(t *testing.T) {
	pf := newProjFixture(t)
	id := pf.withModel(t, "Cube")
	out := pf.ok(t, "slice_project", map[string]any{"project": id})
	front := frontOf(t, out)
	if front["state"] != "finished" {
		t.Fatalf("a fast slice did not return its result:\n%s", out)
	}
	if plates, _ := front["plates"].([]any); len(plates) != 1 || plates[0].(map[string]any)["changes"] == nil {
		t.Errorf("plates lack the filament changes: %v", front["plates"])
	}
	// A slow slice: the wait (1 s) ends first and the reply says how to poll.
	pf.exec.block = make(chan struct{})
	out = pf.ok(t, "slice_project", map[string]any{"project": id, "wait": 1, "thumbnails": false})
	front = frontOf(t, out)
	if front["state"] != "running" || front["job_id"] == nil {
		t.Fatalf("a slow slice did not return the job:\n%s", out)
	}
	if !strings.Contains(out, "still running after 1 s") || !strings.Contains(out, "get_slice_status") {
		t.Errorf("no polling advice:\n%s", out)
	}
	pf.finishJob(t, front["job_id"].(string))
	// background true returns at once, whatever the wait.
	pf.exec.block = make(chan struct{})
	start := time.Now()
	out = pf.ok(t, "slice_project", map[string]any{"project": id, "background": true, "wait": 600})
	if frontOf(t, out)["state"] != "running" || time.Since(start) > 20*time.Second {
		t.Errorf("background did not return at once:\n%s", out)
	}
	close(pf.exec.block)
	pf.exec.block = nil
	for name, args := range map[string]map[string]any{
		"timeout above 1800": {"timeout": 5000}, "wait above 600": {"wait": 601}, "wait below 1": {"wait": 0},
	} {
		args["project"] = id
		if res := call(t, pf.cs, "slice_project", args); !res.IsError {
			t.Errorf("%s was accepted", name)
		}
	}
}

// finishJob releases a blocked fake slicer and waits until the job is finished.
func (pf *projFixture) finishJob(t *testing.T, job string) {
	t.Helper()
	close(pf.exec.block)
	pf.exec.block = nil
	deadline := time.Now().Add(30 * time.Second)
	for time.Now().Before(deadline) {
		if frontOf(t, pf.ok(t, "get_slice_status", map[string]any{"job_id": job}))["state"] == "finished" {
			return
		}
		time.Sleep(20 * time.Millisecond)
	}
	t.Fatalf("job %s did not finish", job)
}

